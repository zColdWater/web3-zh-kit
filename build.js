#!/usr/bin/env node
// web3-zh-kit build — zero dependencies.
//   node build.js   →  dist/zh-module.mjs   (single-file ESM for x402 / Workers gateways)
//                      index.html           (GitHub Pages: in-browser checker, fixer, glossary, support)
//                      glossary/index.html  (static, indexable glossary page)
'use strict';
const fs = require('fs');
const path = require('path');
const root = __dirname;
const rd = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const stripCjs = (src) => src.replace(/\nif \(typeof module[^\n]*\n?$/, '\n');
const fill = (tpl, map) => Object.keys(map).reduce((s, k) => s.split(k).join(map[k]), tpl); // split/join: no `$&` surprises
const esc = (s) => String(s == null ? '' : s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const jsonForScript = (v) => JSON.stringify(v).replace(/</g, '\\u003c').replace(new RegExp('\\u2028', 'g'), '\\u2028').replace(new RegExp('\\u2029', 'g'), '\\u2029');

const core = stripCjs(rd('lib/core.js'));
const payoutLib = stripCjs(rd('lib/payout.js'));
const glossary = JSON.parse(rd('glossary.json'));
const pkg = JSON.parse(rd('package.json'));
const site = JSON.parse(rd('site/site.json'));
const payout = JSON.parse(rd('payout.json'));
const VERSION = pkg.version;
const terms = glossary.terms;
const avoidCount = terms.reduce((n, t) => n + (t.avoid ? t.avoid.length : 0), 0);

// keep the engine version in one place
if (!new RegExp("VERSION = '" + VERSION.replace(/\./g, '\\.') + "'").test(core)) throw new Error('lib/core.js VERSION != package.json version ' + VERSION);

// ---------------------------------------------------------------- 1. x402 module
const adapter = rd('lib/adapter.mjs.tpl');
const mod = [
  '// web3-zh-kit · generated by build.js — edit lib/core.js, glossary.json or lib/adapter.mjs.tpl instead.',
  '// Zero dependencies. Works in Cloudflare Workers, Deno, Bun and Node ≥ 18.',
  'const GLOSSARY = ' + JSON.stringify({ version: glossary.version, terms }) + ';',
  core,
  adapter,
].join('\n');
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist/zh-module.mjs'), mod);

// ---------------------------------------------------------------- 2. website
const CATS = { basics: '基础 Basics', scaling: '扩容 / L2 Scaling', wallet: '钱包 Wallet', security: '安全 Security', tx: '交易 Transactions', defi: 'DeFi',
  token: '代币 Tokens', nft: 'NFT', dao: '治理 DAO', dev: '开发 Dev', names: '专名 Names', ui: '界面用语 UI' };
const catsUsed = [...new Set(terms.map((t) => t.cat))];
for (const c of catsUsed) if (!CATS[c]) throw new Error('missing category label: ' + c);

const searchKey = (t) => [t.en].concat(t.aliases || [], [t.zh_cn, t.zh_tw], t.alt || [], t.avoid || []).join(' ').toLowerCase();
const avoidHtml = (t) => (t.avoid || []).map((a) => '<span class="avoid">' + esc(a) + '</span>').join('、');
const enHtml = (t) => '<b>' + esc(t.en) + '</b>' + (t.aliases && t.aliases.length ? '<br><span class="note">' + esc(t.aliases.join(', ')) + '</span>' : '');

const shortRows = terms.map((t) => '      <tr data-cat="' + esc(t.cat) + '" data-s="' + esc(searchKey(t)) + '"><td>' + enHtml(t) + '</td><td>' + esc(t.zh_cn) + '</td><td>' + esc(t.zh_tw) + '</td><td>' + avoidHtml(t) + '</td></tr>').join('\n');
const catOptions = catsUsed.map((c) => '<option value="' + c + '">' + esc(CATS[c]) + '</option>').join('');

const examples = { en: rd('examples/en.json'), zh: rd('examples/zh-CN.bad.json') };
const data = 'var GLOSSARY = ' + jsonForScript({ version: glossary.version, terms }) + ';\nvar PAYOUT = ' + jsonForScript({ evm: payout.evm, solana: payout.solana, bitcoin: payout.bitcoin }) +
  ';\nvar EXAMPLES = ' + jsonForScript(examples) + ';';

const common = { __VERSION__: VERSION, __TERM_COUNT__: String(terms.length), __AVOID_COUNT__: String(avoidCount), __SITE_URL__: site.url, __REPO_URL__: site.repo, __ACTION_REF__: site.action };
const index = fill(rd('site/index.tpl.html'), Object.assign({}, common, {
  '<!--__GLOSSARY_ROWS__-->': shortRows, __CAT_OPTIONS__: catOptions, '/*__CORE__*/': core, '/*__PAYOUT_LIB__*/': payoutLib, '/*__DATA__*/': data,
}));
fs.writeFileSync(path.join(root, 'index.html'), index);

const sections = catsUsed.map((c) => {
  const rows = terms.filter((t) => t.cat === c).map((t) => {
    const alt = (t.alt || []).filter((a) => a !== t.zh_cn && a !== t.zh_tw);
    return '      <tr data-s="' + esc(searchKey(t)) + '"><td>' + enHtml(t) + '</td><td>' + esc(t.zh_cn) + '</td><td>' + esc(t.zh_tw) + '</td><td>' + (alt.length ? esc(alt.join('、')) : '') +
      (t.keep_en ? (alt.length ? '<br>' : '') + '<span class="note">可保留英文</span>' : '') + '</td><td>' + avoidHtml(t) + '</td><td class="note">' + esc(t.note || '') + '</td></tr>';
  }).join('\n');
  return '  <section data-cat="' + c + '">\n  <h2 id="' + c + '">' + esc(CATS[c]) + '</h2>\n  <div class="tblwrap"><table>\n    <thead><tr><th>English</th><th>简体 zh-CN</th><th>繁體 zh-TW</th><th>也可以</th><th>常见误译</th><th>说明</th></tr></thead>\n    <tbody>\n' + rows + '\n    </tbody>\n  </table></div>\n  </section>';
}).join('\n');
fs.mkdirSync(path.join(root, 'glossary'), { recursive: true });
fs.writeFileSync(path.join(root, 'glossary/index.html'), fill(rd('site/glossary.tpl.html'), Object.assign({}, common, { __SECTIONS__: sections })));

console.log('built dist/zh-module.mjs (' + (mod.length / 1024).toFixed(1) + ' KB), index.html (' + (index.length / 1024).toFixed(1) + ' KB), glossary/index.html · ' + terms.length + ' terms, ' + avoidCount + ' known mistranslations, v' + VERSION);
